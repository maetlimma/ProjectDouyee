// Renders the brochure PDF in reference/ to JPG pages in public/assets and writes the page manifest.
// Usage: bun run brochure:build [path/to/file.pdf]
import * as mupdf from 'mupdf';
import { readdir, unlink } from 'node:fs/promises';
import { join } from 'node:path';
import { brochurePageFilename, BROCHURE_FILE_PATTERN } from '../public/brochure.logic';

const root = join(import.meta.dir, '..');
const referenceDir = join(root, 'reference');
const assetsDir = join(root, 'public/assets');
const manifestPath = join(root, 'public/brochure.pages.ts');
const TARGET_HEIGHT = 1400;
const JPEG_QUALITY = 75;

async function findPdf(): Promise<string> {
  const arg = process.argv[2];
  if (arg) return arg;
  const pdfs = (await readdir(referenceDir)).filter((f) => f.toLowerCase().endsWith('.pdf')).sort();
  if (pdfs.length === 0) throw new Error(`No PDF found in ${referenceDir}`);
  if (pdfs.length > 1) throw new Error(`Several PDFs in ${referenceDir} (${pdfs.join(', ')}). Pass the brochure path explicitly.`);
  return join(referenceDir, pdfs[0]);
}

const pdfPath = await findPdf();
const doc = mupdf.Document.openDocument(await Bun.file(pdfPath).arrayBuffer(), 'application/pdf');
const count = doc.countPages();
let width = 0;
let height = 0;
let totalBytes = 0;

for (let i = 0; i < count; i++) {
  const page = doc.loadPage(i);
  const [x0, y0, x1, y1] = page.getBounds();
  const scale = TARGET_HEIGHT / (y1 - y0);
  const pixmap = page.toPixmap(mupdf.Matrix.scale(scale, scale), mupdf.ColorSpace.DeviceRGB, false, true);
  const jpeg = pixmap.asJPEG(JPEG_QUALITY);
  if (i === 0) {
    width = pixmap.getWidth();
    height = pixmap.getHeight();
  }
  await Bun.write(join(assetsDir, brochurePageFilename(i)), jpeg);
  totalBytes += jpeg.byteLength;
  console.info(`page ${i + 1}/${count} ${Math.round(((x1 - x0) * scale))}x${TARGET_HEIGHT} ${(jpeg.byteLength / 1024).toFixed(0)} KB`);
}

// Remove pages left over from a previous, longer brochure
for (const file of await readdir(assetsDir)) {
  const match = BROCHURE_FILE_PATTERN.exec(file);
  if (match && Number(match[1]) > count) {
    await unlink(join(assetsDir, file));
    console.info(`removed stale ${file}`);
  }
}

await Bun.write(
  manifestPath,
  `// Generated by scripts/build-brochure.ts. Do not edit by hand.\n` +
    `export const BROCHURE_PAGES = { count: ${count}, width: ${width}, height: ${height} } as const;\n`
);

console.info(`Wrote ${count} pages, ${(totalBytes / 1024 / 1024).toFixed(1)} MB total, manifest at public/brochure.pages.ts`);
